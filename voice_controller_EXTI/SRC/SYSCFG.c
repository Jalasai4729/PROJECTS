void KM_SYSCFG_CONFIG()
{
	 //GPIOC_PUPDR REGISTERS
	
	//GPIOC_PUPDR &=~(0x003f0000);//CLEAR 16-21 POSITIONS PC 8_9_10
	//GPIOC_PUPDR |=(0x00150000);//SET 01 ON 16_21 POSITIONS PC 8_9_10

	KM_GPIO_PORT_CONFIG(GPIOA,IN,6);//MODEER REGESTER SET PA6 IR SENSOR
	KM_GPIO_PORT_CONFIG(GPIOA,IN,7);//MODEER REGESTER SET PA7 MQ3 SENSOR


	  RCC_APB2ENR |= (1 << 14);//SET CLOCK FOR SYSCFG 14TH BIT

	 //SYSTEM CONFIGURARTIN PA 6-7
 SYSCFG_EXTICR2 &=~(0xff00);//CLEAR
 SYSCFG_EXTICR2 |=(0x0000);//SET ON 0000 PA 6-7 BITS POSITION
	
		 EXTI_FTSR |=(0x3<<6);   // SET FTSR PA 6-7
	 	 EXTI_RTSR |=(0x3<<6);   // SET FTSR PA 6-7

    	EXTI_IMR |=(0x3<<6);     //SER IMR PA6 PA7

	// NVIC ENABLE
		NVIC_ISER0 |=(0x1<<23); //BASED ON VRCTRO TABLE SET 23 BIT
		NVIC_ISER1 |=(0x1<<8);
}
